//! QDirStat's cache file, version 2.0 (`[qdirstat 2.0 cache file]`): a line
//! an entry, `type path size uid gid perm mtime` and the optional
//! `blocks:` and `links:` fields, tab-separated.
//!
//! - **A directory's line** names it by its absolute path and comes before
//!   its entries, which name themselves by their names, files first, as the
//!   format suggests.
//! - **Sizes** are each entry's own apparent bytes (`st_size`); `blocks:`
//!   (512-byte blocks on disk) appears only for a sparse file, one with
//!   fewer bytes on disk than its length, as the format allows: a file with
//!   more bytes on disk than its length is not representable.
//! - **uid, gid and permissions** are mandatory in 2.0, so the export needs
//!   a scan taken with `--attrs full` (`attrs_not_collected` otherwise);
//!   the mode also gives a special file's type (`BlockDev`, `CharDev`,
//!   `FIFO`, `Socket`).
//! - **Paths and names** are URL-encoded: every byte outside printable
//!   ASCII, a blank and `%` as `%XX`.
//! - **mtime** is whole seconds, in hex.

// QDirStat is a name, not code.
#![allow(clippy::doc_markdown)]

use std::fmt::Write as _;
use std::io::Write;

use duscope_walk::Attrs;

use super::{Paths, Row, RowKind, seconds, walk};
use crate::CoreError;
use crate::index::Index;

/// Writes the entries from `base` down to `out`.
///
/// # Errors
///
/// [`CoreError::AttrsNotCollected`] for a scan without `--attrs full`, and
/// when the index cannot be read or `out` written.
pub fn write(
    index: &Index,
    base: u32,
    version: &str,
    out: &mut dyn Write,
) -> Result<(), CoreError> {
    if index.attrs() != Attrs::Full {
        return Err(CoreError::AttrsNotCollected("export --format qdirstat"));
    }
    write!(
        out,
        "[qdirstat 2.0 cache file]\n\
         # Generated by duscope {version}\n\
         # Do not edit!\n\
         #\n\
         # Type\tpath\tsize\tuid\tgid\tperm.\tmtime\t<optional fields>\n\n"
    )?;
    let mut paths = Paths::default();
    walk(index, base, |row| {
        let path = paths.path(row);
        let mut line = String::new();
        let (kind, name) = if row.dir.is_some() {
            ("D", encode(&path))
        } else {
            (kind(row), encode(&row.name))
        };
        let mtime = seconds(row.mtime_ns);
        let mtime = if mtime >= 0 {
            format!("0x{mtime:x}")
        } else {
            mtime.to_string()
        };
        let _ = write!(
            line,
            "{kind}\t{name}\t{}\t{}\t{}\t{:04o}\t{mtime}",
            row.apparent,
            row.uid.unwrap_or(0),
            row.gid.unwrap_or(0),
            row.mode.unwrap_or(0) & 0o7777,
        );
        if row.dir.is_none() {
            if row.kind == RowKind::File && row.allocated < row.apparent {
                let _ = write!(line, "\tblocks: {}", row.allocated / 512);
            }
            if row.nlink > 1 {
                let _ = write!(line, "\tlinks: {}", row.nlink);
            }
        }
        line.push('\n');
        out.write_all(line.as_bytes())?;
        Ok(())
    })
}

/// The type a non-directory's line starts with: from its mode, which the
/// export requires.
fn kind(row: &Row) -> &'static str {
    const FORMAT: u32 = 0o170_000;
    match row.mode.map(|mode| mode & FORMAT) {
        Some(0o120_000) => "L",
        Some(0o060_000) => "BlockDev",
        Some(0o020_000) => "CharDev",
        Some(0o010_000) => "FIFO",
        Some(0o140_000) => "Socket",
        Some(_) => "F",
        None => match row.kind {
            RowKind::Symlink => "L",
            _ => "F",
        },
    }
}

/// `bytes` URL-encoded: printable ASCII but `%` as it is, every other byte
/// as `%XX`.
fn encode(bytes: &[u8]) -> String {
    let mut out = String::with_capacity(bytes.len());
    for &b in bytes {
        if b.is_ascii_graphic() && b != b'%' {
            out.push(char::from(b));
        } else {
            let _ = write!(out, "%{b:02X}");
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::encode;

    #[test]
    fn p2_cli_02_qdirstat_names_are_url_encoded() {
        assert_eq!(encode(b"with blank"), "with%20blank");
        assert_eq!(encode(b"with%percent"), "with%25percent");
        assert_eq!(encode(b"tab\tand\nline"), "tab%09and%0Aline");
        assert_eq!(encode(b"caf\xc3\xa9"), "caf%C3%A9");
        assert_eq!(encode(b"/a/b.txt"), "/a/b.txt");
    }
}
